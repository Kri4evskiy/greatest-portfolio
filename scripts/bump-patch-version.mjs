import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)
const rootDir = resolve(__dirname, '..')

const rootPkgPath = resolve(rootDir, 'package.json')
const sharedVersionPath = resolve(rootDir, 'packages/shared-schemas/src/version.ts')

function parseAndBumpPatch(versionString) {
  const parts = versionString.trim().split('.')
  if (parts.length !== 3) {
    throw new Error(`Invalid semver version in package.json: "${versionString}"`)
  }
  const major = Number.parseInt(parts[0], 10)
  const minor = Number.parseInt(parts[1], 10)
  const patch = Number.parseInt(parts[2], 10)

  if (Number.isNaN(major) || Number.isNaN(minor) || Number.isNaN(patch)) {
    throw new Error(`Non-numeric semver components in: "${versionString}"`)
  }

  return `${major}.${minor}.${patch + 1}`
}

function main() {
  const shouldStage = process.argv.includes('--stage')
  const rawPkg = readFileSync(rootPkgPath, 'utf8')
  const pkg = JSON.parse(rawPkg)

  const currentVersion = typeof pkg.version === 'string' ? pkg.version : '0.0.1'
  const nextVersion = parseAndBumpPatch(currentVersion)

  pkg.version = nextVersion
  writeFileSync(rootPkgPath, `${JSON.stringify(pkg, null, 2)}\n`, 'utf8')

  const filesToStage = [rootPkgPath]

  // Also synchronize version constant in packages/shared-schemas if present or create directory
  const sharedSrcDir = dirname(sharedVersionPath)
  if (existsSync(resolve(rootDir, 'packages/shared-schemas')) || existsSync(sharedSrcDir)) {
    mkdirSync(sharedSrcDir, { recursive: true })
    const versionFileContent = `// Auto-generated by scripts/bump-patch-version.mjs — DO NOT EDIT MANUALLY\nexport const APP_VERSION = '${nextVersion}' as const\n`
    writeFileSync(sharedVersionPath, versionFileContent, 'utf8')
    filesToStage.push(sharedVersionPath)
  }

  if (shouldStage) {
    try {
      execFileSync('git', ['add', ...filesToStage], { cwd: rootDir, stdio: 'inherit' })
    } catch {
      // Ignore git staging errors if called outside a git commit context
    }
  }

  console.log(`[version-bump] ${currentVersion} -> ${nextVersion}`)
}

main()
