import { execSync } from 'node:child_process';
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const rootDir = process.cwd();
const envExamplePath = resolve(rootDir, '.env.example');
const envPath = resolve(rootDir, '.env');
const rootPkgPath = resolve(rootDir, 'package.json');
const sharedVersionPath = resolve(rootDir, 'packages/shared-schemas/src/version.ts');

function syncEnvFile() {
  if (!existsSync(envPath) && existsSync(envExamplePath)) {
    copyFileSync(envExamplePath, envPath);
    console.log('[setup] Created .env from .env.example');
  }
}

function syncVersionConstant() {
  if (!existsSync(rootPkgPath) || !existsSync(sharedVersionPath)) {
    return;
  }
  const pkg = JSON.parse(readFileSync(rootPkgPath, 'utf8'));
  const version = typeof pkg.version === 'string' ? pkg.version : '0.1.0';
  const expectedContent = `// Auto-generated by scripts/bump-patch-version.mjs — DO NOT EDIT MANUALLY\nexport const APP_VERSION = '${version}' as const;\n`;
  const currentContent = readFileSync(sharedVersionPath, 'utf8');
  if (currentContent !== expectedContent) {
    writeFileSync(sharedVersionPath, expectedContent, 'utf8');
    console.log(`[setup] Synced APP_VERSION = '${version}' in packages/shared-schemas`);
  }
}

function runStep(label, command) {
  console.log(`[setup] ${label}...`);
  execSync(command, { cwd: rootDir, stdio: 'inherit' });
}

function main() {
  syncEnvFile();
  syncVersionConstant();
  runStep(
    'Building @repo/shared-schemas (Zod contracts)',
    'pnpm --filter @repo/shared-schemas build',
  );
  runStep('Generating Prisma Client (@repo/api)', 'pnpm --filter @repo/api prisma:generate');
  console.log('[setup] Monorepo workspace is ready! Run "pnpm run dev" to start all services.');
}

main();
